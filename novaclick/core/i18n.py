_current = "en"


def normalize_language(code: str | None) -> str:
    """Return a supported locale code, tolerating ``pt_BR`` style values."""
    if not code:
        return "en"
    cleaned = str(code).strip().replace("_", "-")
    lowered = cleaned.lower()
    for candidate in LANGUAGES:
        if candidate.lower() == lowered:
            return candidate
    # Language-only fallback ("de-AT" -> "de").
    base = lowered.split("-", 1)[0]
    for candidate in LANGUAGES:
        if candidate.lower() == base:
            return candidate
    return "en"


def set_language(code: str | None) -> str:
    """Select the active locale and return the normalized code."""
    global _current
    _current = normalize_language(code)
    return _current


def get_language() -> str:
    return _current


def language_name(code: str | None = None, native: bool = True) -> str:
    code = normalize_language(code or _current)
    native_name, english_name = LANGUAGES.get(code, LANGUAGES["en"])
    return native_name if native else english_name


def choices() -> Iterable[tuple[str, str, str]]:
    """Yield ``(code, native, english)`` for the language picker."""
    for code, (native, english) in LANGUAGES.items():
        yield code, native, english


def tr(key: str, /, **values: object) -> str:
    """Translate *key* in the active locale, falling back to English."""
    text = TRANSLATIONS.get(_current, {}).get(key)
    if text is None:
        text = ENGLISH.get(key, key)
    if values:
        try:
            text = text.format(**values)
        except (KeyError, ValueError):
            pass
    return text


